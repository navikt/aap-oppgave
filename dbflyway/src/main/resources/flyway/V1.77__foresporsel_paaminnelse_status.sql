UPDATE OPPGAVE
SET FORESPORSEL_PAAMINNELSE_STATUS = CASE
    WHEN NOT FORESPORSEL_SENDT_TIL_BEHANDLER THEN NULL
    WHEN FORESPORSEL_PAAMINNELSE_AVBRUTT IS TRUE THEN 'AVBRUTT'
    WHEN FORESPORSEL_PAAMINNELSE_DATO::DATE <= CURRENT_DATE THEN 'SENDT'
    ELSE 'PLANLAGT'
END
WHERE FORESPORSEL_PAAMINNELSE_STATUS IS NULL;


